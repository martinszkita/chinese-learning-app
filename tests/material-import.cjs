const assert=require('node:assert/strict');
const matching=require('../js/services/material-matching.js');
const OpenCC=require('../vendor/pinyin/opencc.js');
const traditional=OpenCC.Converter({from:'cn',to:'tw'});
assert.equal(traditional('学校和火车'),'學校和火車');
const words=matching.segment('我在學校學中文。','word');assert(words.includes('學校'));assert.equal(words.join(''),'我在學校學中文');
assert.deepEqual(matching.segment('你好。你去哪裡？\n今天上課','sentence'),['你好。','你去哪裡？','今天上課']);
assert.throws(()=>matching.segment('中'.repeat(20001),'word'),/20,000/);
assert.throws(()=>matching.segment(Array(501).fill('你好。').join('\n'),'sentence'),/500/);
const entry={id:'1',chineseTraditional:'學校',chineseSimplified:'学校',aliases:[{chinese:'學 堂'}]};
assert.equal(matching.matches({chineseTraditional:'学校'},[entry])[0].id,'1');
assert.equal(matching.matches({chineseTraditional:'學堂'},[entry])[0].id,'1');
assert.equal(matching.matches({chineseTraditional:'你好'},[{chineseTraditional:'你好。'}]).length,0);
assert.equal(matching.normalize('Ａ　Ｂ'),'AB');
console.log('PASS: Chinese word/sentence segmentation, paragraphs, input limits, both scripts, aliases and punctuation-preserving matching');
